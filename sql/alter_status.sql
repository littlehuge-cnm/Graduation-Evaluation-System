-- =====================================================================
-- 本科生毕业设计评价系统 新增状态字段脚本
-- 说明：将各表状态字段用数字编码（1/2/3...）表示
-- 执行顺序：在 init.sql 之后执行，或独立执行
-- =====================================================================

USE graduation_evaluation;

-- ---------------------------------------------------------------------
-- 1. 账号状态字段（t_admin / t_teacher / t_student）
--    1=启用  2=禁用
-- ---------------------------------------------------------------------
ALTER TABLE t_admin
    MODIFY COLUMN account_status TINYINT NOT NULL DEFAULT 1 COMMENT '账号状态（1=启用/2=禁用）';

ALTER TABLE t_teacher
    MODIFY COLUMN account_status TINYINT NOT NULL DEFAULT 1 COMMENT '账号状态（1=启用/2=禁用）';

ALTER TABLE t_student
    MODIFY COLUMN account_status TINYINT NOT NULL DEFAULT 1 COMMENT '账号状态（1=启用/2=禁用）';

-- ---------------------------------------------------------------------
-- 2. 学生整体进度状态字段（t_student）
--    1=待分配  2=进行中  3=待答辩  4=已完成  5=已弃做
-- ---------------------------------------------------------------------
ALTER TABLE t_student
    MODIFY COLUMN overall_status TINYINT NOT NULL DEFAULT 1 COMMENT '整体进度状态（1=待分配/2=进行中/3=待答辩/4=已完成/5=已弃做）';

-- ---------------------------------------------------------------------
-- 3. 教师分组状态字段（t_teacher_group）
--    1=待启用  2=已启用  3=已停用
-- ---------------------------------------------------------------------
ALTER TABLE t_teacher_group
    MODIFY COLUMN group_status TINYINT NOT NULL DEFAULT 1 COMMENT '分组状态（1=待启用/2=已启用/3=已停用）';

-- ---------------------------------------------------------------------
-- 4. 师生关系状态字段（t_teacher_student）
--    1=生效  2=已解除
-- ---------------------------------------------------------------------
ALTER TABLE t_teacher_student
    MODIFY COLUMN relation_status TINYINT NOT NULL DEFAULT 1 COMMENT '关系状态（1=生效/2=已解除）';

-- ---------------------------------------------------------------------
-- 5. 文档状态字段（t_document）
--    1=草稿  2=已提交
-- ---------------------------------------------------------------------
ALTER TABLE t_document
    MODIFY COLUMN status TINYINT NOT NULL DEFAULT 1 COMMENT '文档状态（1=草稿/2=已提交）';

-- ---------------------------------------------------------------------
-- 6. 课题审批状态字段（t_document，仅任务书使用）
--    1=待系审  2=系通过  3=系驳回  4=待院审  5=院通过  6=院驳回
-- ---------------------------------------------------------------------
ALTER TABLE t_document
    MODIFY COLUMN approval_status TINYINT DEFAULT NULL COMMENT '课题审批状态（1=待系审/2=系通过/3=系驳回/4=待院审/5=院通过/6=院驳回），仅任务书使用';

-- ---------------------------------------------------------------------
-- 7. 评价记录状态字段（t_score_record）
--    1=暂存  2=已确认
-- ---------------------------------------------------------------------
ALTER TABLE t_score_record
    MODIFY COLUMN record_status TINYINT NOT NULL DEFAULT 1 COMMENT '记录状态（1=暂存/2=已确认）';

-- ---------------------------------------------------------------------
-- 8. 环节状态字段（t_stage_status）
--    1=未开始  2=进行中  3=已完成
-- ---------------------------------------------------------------------
ALTER TABLE t_stage_status
    MODIFY COLUMN status TINYINT NOT NULL DEFAULT 1 COMMENT '状态（1=未开始/2=进行中/3=已完成）';

-- ---------------------------------------------------------------------
-- 9. 学生组号字段允许为空（t_student）
--    删除学生分组时，组内学生的 student_group_id 置空
-- ---------------------------------------------------------------------
ALTER TABLE t_student
    MODIFY COLUMN student_group_id INT DEFAULT NULL COMMENT '所属学生组号（删除分组时置空）';


-- =====================================================================
-- 状态编码对照表
-- =====================================================================
--
-- 【1】account_status（账号状态）
--     1=启用    2=禁用
--
-- 【2】overall_status（学生整体进度状态）
--     1=待分配  2=进行中  3=待答辩  4=已完成  5=已弃做
--
-- 【3】group_status（教师分组状态）
--     1=待启用  2=已启用  3=已停用
--
-- 【4】relation_status（师生关系状态）
--     1=生效    2=已解除
--
-- 【5】status（文档状态，t_document）
--     1=草稿    2=已提交
--
-- 【6】approval_status（课题审批状态，仅任务书）
--     1=待系审  2=系通过  3=系驳回  4=待院审  5=院通过  6=院驳回
--
-- 【7】record_status（评价记录状态）
--     1=暂存    2=已确认
--
-- 【8】status（环节状态，t_stage_status）
--     1=未开始  2=进行中  3=已完成
